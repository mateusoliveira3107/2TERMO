CALL CONTAR_PRODUTOS_ATIVOS(@TOTAL); -- @TOTAL É A 'VARIÁVEL' QUE VOCÊ DEFINIU QUE A FUNÇÃO DEVOLVERIA À VOCÊ, ARMAZENANDO OS VALORES DA FUNÇÃO, CASO CHAMASSE @TOTAL, ELE EXIBIRIA A QUANTIDADE DE PRODUTOS ATIVOS, POIS FOI DEFINIDO COM "SELECT COUNT(*) INTO P_TOTAL FROM PRODUTO WHERE ATIVO = TRUE;"
