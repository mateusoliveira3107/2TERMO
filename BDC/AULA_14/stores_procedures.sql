-- EX 9: PROCEDURE PARA UPDATE
DELIMITER $$
CREATE PROCEDURE ATUALIZAR_PRECO_PRODUTO (
    IN P_ID_PRODUTO INT,
    IN P_NOVO_PRECO DECIMAL(10, 2)
)
BEGIN
    IF P_ID_PRODUTO > 0 THEN
        UPDATE PRODUTO
        SET PRECO = P_NOVO_PRECO
        WHERE ID_PRODUTO - P_ID_PRODUTO;

        SELECT 'PREÇO ATUALIZADO' AS MENSAGEM;
    ELSE
        SELECT 'PREÇO INVÁLDO' AS MENSAGEM;
    END IF;
END $$
DELIMITER;

CALL ATUALIZAR_PRECO_PRODUTO(1, 9.99);
CALL ATUALIZAR_PRECO_PRODUTO(2, 11.99);
SELECT *
FROM PRODUTO
WHERE ID_PRODUTO = 1 OR ID_PRODUTO = 2;


-- EX 10: PROCEDURE COM REGRA DE NEGÓCIO E REGISTRO DE PEDIDO
DELIMITER $$
CREATE PROCEDURE REGISTRAR_PEDIDO (
    IN P_ID_CLIENTE INT,
    OUT P_ID_PEDIDO INT
)
BEGIN
    START TRANSACTION;
    INSERT INTO PEDIDO (ID_CLIENTE, DATA_PEDIDO, STATUS_PEDIDO) VALUES
    (P_ID_CLIENTE, NOW(), 'ABERTO');

    SET P_ID_PEDIDO = LAST_INSERT_ID();
    COMMIT;
END $$
DELIMITER;

CALL REGISTRAR_PEDIDO(1, @PEDIDO);
SELECT @PEDIDO;