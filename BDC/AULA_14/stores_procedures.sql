DELIMITER $$
CREATE PROCEDURE LISTAR_PRODUTOS()
BEGIN
    SELECT ID_PRODUTO AS CÓDIGO, NOME, PRECO
    FROM PRODUTO
    WHERE ATIVO = TRUE
    ORDER BY NOME;
END
DELIMITER;

CALL LISTAR_PRODUTOS();

DELIMITER $$
CREATE PROCEDURE BUSCAR_PRODUTOS_CATEGORIA (IN P_ID_CATEGORIA INT) -- FUNCIONA COMO UMA FUNÇÃO, RECEBENDO UM PARÂMETRO E EXECUTANDO AÇÕES EM CIMA DELE
BEGIN
    SELECT ID_PRODUTO AS CÓDIGO, NOME, PRECO
    FROM PRODUTO
    WHERE ID_CATEGORIA = P_ID_CATEGORIA
    AND ATIVO = TRUE
    ORDER BY NOME;
END
DELIMITER;

CALL BUSCAR_PRODUTOS_CATEGORIA(1);

