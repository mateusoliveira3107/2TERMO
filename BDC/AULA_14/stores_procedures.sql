CREATE PROCEDURE CONTAR_PRODUTOS_ATIVOS (OUT P_TOTAL INT) -- OUT DEFINE QUE A 'FUNÇÃO' VAI DEVOLVER UM VALOR, NÃO RECEBER
BEGIN
    SELECT COUNT(*)
    INTO P_TOTAL
    FROM PRODUTO
    WHERE ATIVO = TRUE;
END $$
