-- 2. TABELA CLIENTE
CREATE TABLE IF NOT EXISTS CLIENTE (
    ID_CLIENTE INT AUTO_INCREMENT,
    NOME VARCHAR(100) NOT NULL,
    EMAIL VARCHAR(120) NOT NULL UNIQUE,
    TELEFONE VARCHAR(20),
    ATIVO BOOLEAN DEFAULT TRUE,

    CONSTRAINT PK_CLIENTE PRIMARY KEY (ID_CLIENTE),
    CONSTRAINT UK_EMAIL_CLIENTE UNIQUE (EMAIL)
);

-- 3. PLATAFORMA E CATEGORIA
CREATE TABLE IF NOT EXISTS PLATAFORMA (
    ID_PLATAFORMA INT AUTO_INCREMENT,
    NOME VARCHAR(80) NOT NULL UNIQUE,

    CONSTRAINT PK_PLATAFORMA PRIMARY KEY (ID_PLATAFORMA),
    CONSTRAINT UK_NOME_PLATAFORMA UNIQUE (NOME)
);

CREATE TABLE IF NOT EXISTS CATEGORIA (
    ID_CATEGORIA INT AUTO_INCREMENT,
    DESCRICAO VARCHAR(200) NOT NULL UNIQUE,

    CONSTRAINT PK_CATEGORIA PRIMARY KEY (ID_CATEGORIA),
    CONSTRAINT UK_DESCRICAO_CATEGORIA UNIQUE (DESCRICAO)
);

-- 4. TABELA JOGO
CREATE TABLE IF NOT EXISTS JOGO (
    ID_JOGO INT AUTO_INCREMENT,
    TITULO VARCHAR(150) NOT NULL,
    CODIGO_IDENTIFICADOR VARCHAR(15) NOT NULL,
    ANO_LANCAMENTO INT NOT NULL,
    QUANTIDADE INT NOT NULL CHECK (QUANTIDADE >= 0),
    ID_PLATAFORMA INT NOT NULL,
    ID_CATEGORIA INT NOT NULL,

    CONSTRAINT PK_JOGO PRIMARY KEY (ID_JOGO),
    CONSTRAINT CODIGO_JOGO UNIQUE (CODIGO_IDENTIFICADOR),
    CONSTRAINT FK_PLATAFORMA FOREIGN KEY (ID_PLATAFORMA) REFERENCES PLATAFORMA (ID_PLATAFORMA),
    CONSTRAINT FK_CATEGORIA FOREIGN KEY (ID_CATEGORIA) REFERENCES CATEGORIA (ID_CATEGORIA)
);

-- 5. TABELA LOCACAO
CREATE TABLE IF NOT EXISTS LOCACAO (
    ID_LOCACAO INT AUTO_INCREMENT,
    DATA_RETIRADA DATETIME DEFAULT CURRENT_TIMESTAMP,
    DATA_PREVISTA DATE NOT NULL,
    DATA_DEVOLUCAO DATE,
    STATUS_LOCACAO VARCHAR(20) DEFAULT 'ABERTA' CHECK(STATUS_LOCACAO IN ('ABERTA', 'DEVOLVIDA', 'ATRASADA')),
    ID_CLIENTE INT NOT NULL,
    ID_JOGO INT NOT NULL,

    CONSTRAINT PK_LOCACAO PRIMARY KEY (ID_LOCACAO),
    CONSTRAINT FK_CLIENTE_LOCACAO FOREIGN KEY (ID_CLIENTE) REFERENCES CLIENTE (ID_CLIENTE),
    CONSTRAINT FK_JOGO_LOCACAO FOREIGN KEY (ID_JOGO) REFERENCES JOGO (ID_JOGO)
);

